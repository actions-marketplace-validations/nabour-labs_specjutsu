#!/bin/sh
# Print the Homebrew formula for an sj release from its SHA256SUMS (DIST-008, DIST-009).
# Usage: homebrew.sh <version> <SHA256SUMS>
# release.yml pushes the output to nabour-labs/homebrew-tap as Formula/specjutsu.rb.
set -eu
version="${1:?usage: homebrew.sh <version> <SHA256SUMS>}"
version="${version#v}"
sums="${2:?usage: homebrew.sh <version> <SHA256SUMS>}"
url="https://github.com/nabour-labs/specjutsu/releases/download/v$version"

sum() {
  s=$(awk -v a="sj-$1.tar.gz" '$2 == a || $2 == "*" a { print $1 }' "$sums")
  if [ -z "$s" ]; then
    echo "homebrew: SHA256SUMS has no sj-$1.tar.gz" >&2
    exit 1
  fi
  echo "$s"
}

# Resolve every checksum before printing anything, so a failure leaves stdout empty.
mac_arm=$(sum aarch64-apple-darwin)
mac_x64=$(sum x86_64-apple-darwin)
linux_arm=$(sum aarch64-unknown-linux-gnu)
linux_x64=$(sum x86_64-unknown-linux-musl)

cat <<EOF
# Generated by scripts/release/homebrew.sh in nabour-labs/specjutsu. Do not edit.
class Specjutsu < Formula
  desc "Makes AI coding agents prove their work: every spec scenario needs a failing test first"
  homepage "https://nabour-labs.github.io/specjutsu/"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$url/sj-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$url/sj-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_x64"
    end
  end

  on_linux do
    on_arm do
      url "$url/sj-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$url/sj-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_x64"
    end
  end

  def install
    bin.install "sj"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sj --version")
  end
end
EOF
